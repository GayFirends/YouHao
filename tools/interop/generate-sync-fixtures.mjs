const envelope = await encryptSyncPayload(PAYLOAD, PASSPHRASE)

// Prove the recorded envelope round-trips through the legacy implementation before writing it.
const roundTripped = await decryptSyncDocument(structuredClone(envelope), PASSPHRASE)
if (JSON.stringify(roundTripped) !== JSON.stringify(PAYLOAD)) {
  throw new Error('legacy implementation failed to round-trip its own envelope')
}

const fixture = {
  $comment:
    'Generated by tools/interop/generate-sync-fixtures.mjs from the legacy src/services/sync-crypto.ts. ' +
    'Salt and IV are pinned; PBKDF2-HMAC-SHA-256 at 310000 iterations over UTF-8 passphrase bytes.',
  passphrase: PASSPHRASE,
  plaintext: PAYLOAD,
  envelope,
}

const destination = resolve(repository, 'domain/src/test/resources/sync-crypto-reference.json')
mkdirSync(dirname(destination), { recursive: true })
writeFileSync(destination, JSON.stringify(fixture, null, 2) + '\n', 'utf8')
console.log(`wrote ${destination}`)
console.log(`salt=${envelope.crypto.salt} iv=${envelope.crypto.iv}`)
console.log(`ciphertext=${envelope.ciphertext}`)

// ---------------------------------------------------------------------------
// The other half of the handshake: read back an envelope this repository's Kotlin
// implementation produced and decrypt it here, with the legacy code.
// Produced by `SyncCryptoTest.writesAnEnvelopeForTheLegacyClientToRead`, so run
// `gradlew :domain:test` before this script to exercise it.
// ---------------------------------------------------------------------------
const kotlinEnvelopePath = resolve(repository, 'domain/build/interop/kotlin-envelope.json')
if (!existsSync(kotlinEnvelopePath)) {
  console.log(`\nSKIPPED: ${kotlinEnvelopePath} not found — run "gradlew :domain:test" first.`)
} else {
  const kotlinEnvelope = JSON.parse(readFileSync(kotlinEnvelopePath, 'utf8'))
  const decrypted = await decryptSyncDocument(kotlinEnvelope, PASSPHRASE)
  const matches = JSON.stringify(decrypted) === JSON.stringify(PAYLOAD)
  console.log(
    matches
      ? '\nPASS: the legacy client decrypted and validated the Kotlin-written envelope.'
      : '\nFAIL: the legacy client could not reproduce the payload from the Kotlin envelope.',
  )
  if (!matches) {
    console.log(`  expected ${JSON.stringify(PAYLOAD)}`)
    console.log(`  actual   ${JSON.stringify(decrypted)}`)
    process.exitCode = 1
  }
}
