// Generates `domain/src/test/resources/sync-crypto-reference.json` from the LEGACY
// TypeScript implementation (`src/services/sync-crypto.ts`), so the Kotlin port of the
// AES-GCM container can be proven byte-compatible with files the old WebView client wrote.
//
// Requires the legacy `src/` tree to still be present. Run from the repository root:
//
//     node tools/interop/generate-sync-fixtures.mjs
//
// The salt and IV are pinned via a stubbed `crypto.getRandomValues` so the recorded
// ciphertext is reproducible; AES-GCM is deterministic for a fixed key, IV and plaintext.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { register } from 'node:module'

const here = dirname(fileURLToPath(import.meta.url))
const repository = resolve(here, '..', '..')

register('./ts-resolve-hook.mjs', import.meta.url)

const realCrypto = globalThis.crypto
let entropyCall = 0
Object.defineProperty(globalThis, 'crypto', {
  configurable: true,
  writable: true,
  value: {
    subtle: realCrypto.subtle,
    randomUUID: () => realCrypto.randomUUID(),
    getRandomValues: (array) => {
      entropyCall += 1
      for (let index = 0; index < array.length; index += 1) {
        array[index] = (entropyCall * 37 + index * 11) & 0xff
      }
      return array
    },
  },
})

const { encryptSyncPayload, decryptSyncDocument } = await import(
  pathToFileURL(resolve(repository, 'src/services/sync-crypto.ts')).href
)

const PASSPHRASE = 'youhao-sync-test-passphrase'
